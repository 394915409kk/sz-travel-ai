def build_records(scripts):
    records = []
    for (sc, line, q, ans, src) in scripts:
        records.append({
            "values": {
                "场景": sc,
                "意向线路": line,
                "客户问题示例": q,
                "标准话术（可直接复制发送）": ans,
                "采纳状态": S,
                "采纳次数": 0,
                "来源": src,
            }
        })
    return records

def run(records):
    total = len(records)
    for i in range(0, total, BATCH):
        batch = records[i:i+BATCH]
        payload = json.dumps(batch, ensure_ascii=False)
        cmd = [
            "wecom-cli", "smartsheet", "records", "add",
            "--docid", DOCID,
            "--sheet-title", SHEET_TITLE,
            "--key-type", "field_title",
            "--records", payload,
        ]
        r = subprocess.run(cmd, capture_output=True, text=True)
        try:
            resp = json.loads(r.stdout)
            if resp.get("errcode") == 0:
                print(f"[OK] batch {i//BATCH+1}: {len(batch)} records written (total {i+len(batch)}/{total})")
            else:
                print(f"[ERR] batch {i//BATCH+1}: {resp.get('errmsg')}")
                print(r.stdout[:800])
                sys.exit(1)
        except Exception as e:
            print(f"[EXC] batch {i//BATCH+1}: {e}")
            print(r.stdout[:800])
            sys.exit(1)

if __name__ == "__main__":
    records = build_records(SCRIPTS)
    print(f"Total scripts to write: {len(records)}")
    run(records)
    print("All done.")
